async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:47831')
  await page.evaluate(() => localStorage.removeItem('qoder-ui-fixture'))
  await page.reload()
  await page.getByRole('combobox', { name: '上下文窗口', exact: true }).first().selectOption('500000')
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('qoder-ui-fixture')).providers['qoder-cn'].contextWindowOverride === 500000)
  await page.locator('.qoder-models > summary').click()
  await page.locator('.qoder-model > summary').click()
  assert(await page.getByText('本地预算覆盖：', { exact: false }).isVisible(), '500K unsupported-tier warning missing')
  await page.getByRole('combobox', { name: '上下文窗口', exact: true }).first().selectOption('1000000')
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('qoder-ui-fixture')).providers['qoder-cn'].contextWindowOverride === 1000000)
  assert(await page.getByText('本地预算覆盖：', { exact: false }).count() === 0, 'supported 1M tier is incorrectly warned')
  await page.getByRole('combobox', { name: '最大输出', exact: true }).first().selectOption('8192')
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('qoder-ui-fixture')).providers['qoder-cn'].maxOutputTokens === 8192)
  await page.reload()
  assert(await page.getByRole('combobox', { name: '上下文窗口', exact: true }).first().inputValue() === '1000000', 'context did not persist on reload')
  assert(await page.getByRole('combobox', { name: '最大输出', exact: true }).first().inputValue() === '8192', 'output did not persist on reload')
  const context = page.locator('.qoder-capacity-input').first()
  await context.locator('select').selectOption('custom')
  await context.locator('input').fill('-1')
  assert(await context.getByRole('button').isDisabled(), 'negative custom value accepted')
  await context.locator('input').fill('750000')
  await context.getByRole('button').click()
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('qoder-ui-fixture')).providers['qoder-cn'].contextWindowOverride === 750000)
  await page.getByRole('button', { name: '恢复自动', exact: true }).first().click()
  await page.waitForFunction(() => !('contextWindowOverride' in JSON.parse(localStorage.getItem('qoder-ui-fixture')).providers['qoder-cn']))
  assert(await page.getByRole('combobox', { name: '最大输出', exact: true }).first().inputValue() === 'auto', 'restore automatic did not remove both fields')
  await page.getByRole('checkbox', { name: '在侧边栏显示额度卡片' }).check()
  await page.waitForSelector('[data-qoder-quota-card]')
  await page.setViewportSize({ width: 1120, height: 1200 })
  await page.screenshot({ path: 'output/playwright/settings-light-zh.png', fullPage: true })
  await page.getByRole('button', { name: '查看详情', exact: true }).click()
  await page.getByRole('heading', { name: 'Qoder CN 套餐与额度' }).waitFor()
  await page.screenshot({ path: 'output/playwright/quota-light-zh.png', fullPage: true })
  await page.getByRole('button', { name: '返回会话' }).click()
  await page.getByRole('heading', { name: '模型与容量' }).waitFor()
  await page.evaluate(() => window.qoderFixture.setQuotaOffline(true))
  await page.locator('.qoder-section').filter({ has: page.getByRole('heading', { name: '额度概览', exact: true }) }).getByRole('button', { name: '刷新', exact: true }).click()
  await page.getByText('当前显示上次成功数据；本次刷新失败。', { exact: true }).waitFor()
  assert(await page.getByText('840 / 3,000', { exact: true }).isVisible(), 'quota refresh failure erased previous data')
  await page.evaluate(() => window.qoderFixture.setQuotaOffline(false))
  await page.goto('http://127.0.0.1:47831/?lang=en&theme=dark')
  await page.getByRole('heading', { name: 'Model capacity' }).waitFor()
  await page.screenshot({ path: 'output/playwright/settings-dark-en.png', fullPage: true })
  await page.goto('http://127.0.0.1:47831/?theme=dark&rail=1')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.qoder-models > summary').click()
  await page.locator('.qoder-model > summary').click()
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'narrow layout has horizontal overflow')
  await page.screenshot({ path: 'output/playwright/settings-dark-narrow-zh.png', fullPage: true })
  await page.goto('http://127.0.0.1:47831/?readonly=1')
  assert(await page.getByRole('combobox', { name: '上下文窗口', exact: true }).first().isDisabled(), 'readonly capacity is editable')
  assert(await page.getByRole('checkbox').isDisabled(), 'readonly toggle is editable')
  await page.goto('http://127.0.0.1:47831/?reject=1')
  await page.getByRole('combobox', { name: '上下文窗口', exact: true }).first().selectOption('500000')
  await page.getByRole('alert').filter({ hasText: 'Fixture write rejection' }).waitFor()
  assert(await page.getByRole('combobox', { name: '上下文窗口', exact: true }).first().inputValue() === 'auto', 'failed preset did not roll back')
  assert(errors.length === 0, errors.join('\n'))
  console.log(JSON.stringify({ checks: 'capacity save/reload/custom/reset, unsupported warning, panel return, stale quota, sidebar forms, readonly/rejected save, bilingual/themes/narrow overflow', screenshots: 4, browserErrors: errors.length }))
}
